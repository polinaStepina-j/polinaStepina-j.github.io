# Использование aggregate
# aggregate(формула, data, FUN)

# Создадим функцию, чтобы aggregate мог вычислить все три статистики сразу
get_group_stats <- function(x) {
  data.frame(
    Mean = mean(x),
    Median = median(x),
    SD = sd(x)
  )
}
# Применим get_group_stats к 'len' по 'supp'
