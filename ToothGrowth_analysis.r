# 5. Создание новой переменной как функцию от существующих

# Создадим новую переменную 'len_per_dose', которая будет представлять
# длину зубов, деленную на дозу. Это может показать - эффективность дозы.
new <- ToothGrowth %>%
  mutate(len_per_dose = len / dose)

print(head(new))

# С помощью комбинации функций summarize() и group_by() представим сводную информацию
# по группам наблюдений.
# Сгруппируем по типу добавки (supp) и дозе (dose) и посчитаем среднее, медиану
# и стандартное отклонение для 'len_per_dose'.
summary_by_group <- new %>%
  group_by(supp, dose) %>%
  summarize(
    mean_len_per_dose = mean(len_per_dose),
    median_len_per_dose = median(len_per_dose),
    sd_len_per_dose = sd(len_per_dose),
    .groups = 'drop' # Убираем группировку после summarize
  )

print(summary_by_group)

# Содержательная интерпретация:
# - Новая переменная 'len_per_dose' позволяет оценить, сколько единиц роста зубов
#   приходится на каждую единицу дозы добавки. Это стандартизует эффект дозы.
# - Из сводной таблицы 'summary_by_group' мы можем увидеть, как меняется
#   "эффективность" добавки в зависимости от ее типа и дозы.
#   Например, для добавки "OJ" при дозе 0.5 среднее 'len_per_dose' составляет около 43.1.
#   При дозе 2.0 для "OJ" это значение падает до 13.06. Это может указывать на
#   нелинейный эффект дозы или на то, что высокие дозы "OJ" не так "эффективны"
#   на единицу дозы, как низкие.
#   Сравнивая "OJ" и "VC" при одинаковых дозах, можно заметить различия в
#   средней 'len_per_dose', что подтверждает, что апельсиновый сок может быть более
#   эффективным на единицу дозы, особенно при низких дозах.
#   Это дает более глубокое понимание взаимодействия между добавкой, дозой и ростом зубов.

























